#!/bin/bash
# Generalize the VM before it becomes a template. Cloud-init stays ENABLED so
# Terraform clones can be configured via guestinfo.userdata/metadata
# (VMware datasource) or a NoCloud seed ISO on Proxmox: hostname, network,
# SSH keys, compose files, etc.
set -euxo pipefail
export DEBIAN_FRONTEND=noninteractive

sudo cloud-init status --wait || true

# SSH: key-only, never passwords. 01- sorts before cloud-init's 50- file, and
# sshd uses the first value it reads.
sudo rm -f /etc/ssh/sshd_config.d/50-cloud-init.conf
echo 'PasswordAuthentication no' | sudo tee /etc/ssh/sshd_config.d/01-no-password.conf > /dev/null
# Locale: use the VM's own. Don't accept the client's LANG/LC_* (macOS sends e.g.
# LC_CTYPE=UTF-8, which isn't a Linux locale: warnings on every login). AcceptEnv
# lines add up, so a drop-in can't undo them; comment them out where they are.
sudo sed -i -E 's/^([[:space:]]*AcceptEnv[[:space:]].*)$/# \1  # vm-portal: VMs use their own locale/' \
  /etc/ssh/sshd_config $(sudo find /etc/ssh/sshd_config.d -name '*.conf' 2>/dev/null)
sudo sshd -t
sudo passwd -l "$USER"

# The installer disables cloud-init on the target; re-enable it and drop the
# installer's config so clones don't reuse it.
sudo rm -f /etc/cloud/cloud.cfg.d/*installer*.cfg \
           /etc/cloud/cloud.cfg.d/*subiquity-disable-cloudinit-networking.cfg \
           /etc/cloud/cloud-init.disabled \
           /etc/cloud/ds-identify.cfg
# Fail the build if anything still disables cloud-init networking.
if sudo grep -rlE 'config:\s*disabled' /etc/cloud/cloud.cfg.d/; then
  echo "cloud-init network config is still disabled by the files above" >&2
  exit 1
fi
# Look for config in VMware guestinfo (Terraform extra_config), or on Proxmox in the
# portal's NoCloud seed ISO (the build sets VMPORTAL_DATASOURCE). Fall back to None,
# which still runs cloud-init with DHCP networking and new host keys.
DS="${VMPORTAL_DATASOURCE:-VMware}"
case "$DS" in VMware|NoCloud) ;; *) echo "bad VMPORTAL_DATASOURCE" >&2; exit 1 ;; esac
echo "datasource_list: [ $DS, None ]" | sudo tee /etc/cloud/cloud.cfg.d/90_dpkg.cfg > /dev/null
echo "cloud-init-base cloud-init-base/datasources multiselect $DS, None" | sudo debconf-set-selections
# cloud-init's default user is "ubuntu"; make it the existing build user so
# user-data without a users: list doesn't create a second account.
sudo tee /etc/cloud/cloud.cfg.d/91-default-user.cfg > /dev/null <<EOF
system_info:
  default_user:
    name: ${USER}
    lock_passwd: true
    groups: [adm, sudo, docker]
    sudo: ["ALL=(ALL) NOPASSWD:ALL"]
    shell: /bin/bash
EOF
ls -la /etc/cloud/ /etc/cloud/cloud.cfg.d/
grep -i cloud-init /proc/cmdline /etc/default/grub /etc/default/grub.d/* 2>/dev/null || true
# Netplan gets regenerated by cloud-init (DHCP unless Terraform passes a network config).
sudo rm -f /etc/netplan/*.yaml

# Packages
sudo apt-get -y autoremove --purge
sudo apt-get -y clean

# Identity: each clone must get its own SSH host keys and machine-id.
# cloud-init regenerates host keys on a new instance's first boot.
sudo rm -f /etc/ssh/ssh_host_*
sudo cloud-init clean --logs --seed
sudo truncate -s 0 /etc/machine-id
sudo rm -f /var/lib/dbus/machine-id
sudo ln -s /etc/machine-id /var/lib/dbus/machine-id

# Logs, history, temp
sudo find /var/log -type f -exec truncate -s 0 {} +
sudo rm -rf /tmp/* /var/tmp/*
rm -f ~/.bash_history
sudo rm -f /root/.bash_history

# Build keys must not reach clones: they get their keys from cloud-init. Our
# SSH session stays open after this, and Packer only needs it to shut down.
rm -f ~/.ssh/authorized_keys

sudo sync
